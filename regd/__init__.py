"""regd — реестр агентных инструментов с доверием и сроком годности.

Задача выросла из дайджеста музея «RFC-кладбище»
(https://kostyk348.github.io/lost-tech-museum/digests/rfc-graveyard/), записи архива:

  * `uddi` — публичный каталог сервисов без проверки и без срока годности записи
    превратился в свалку: 50 000 записей, живых — единицы; 12.01.2006 публикацию
    выключили. Урок: каталог — это обязательство, поэтому запись здесь аренда.
  * `whoispp` — структурный доступ к реестру проиграл текстовому WHOIS и вернулся
    как RDAP только в 2015. Урок: доступ к реестру — API со структурой, а не разбор
    человеческого вывода (отсюда `--json` и HTTP-фасад).
  * `webintents` — выбор исполнителя в рантайме; W3C работу свернула, а агентам это
    ровно нужная модель (отсюда `find --verb` и репутация числом).

Модули:
  * `model`     — запись, аренда, репутация, возможность (verb);
  * `store`     — JSON-хранилище с атомарной записью, журнал JSONL, архив `expired`;
  * `handshake` — рукопожатие с challenge и проверка живости;
  * `registry`  — правила реестра + HTTP-фасад (`serve`);
  * `render`    — текстовый вывод для человека;
  * `tools`     — фальшивые инструменты для `demo` и тестов;
  * `__main__`  — CLI: register, find, list, report, renew, gc, serve, demo.
"""
